def new_round(kind, visit_no, on, consultants, target_level):
    return {"type": kind, "visit_no": visit_no, "date": on, "consultants": consultants,
            "target_level": target_level, "recommended_level": None, "results": {}, "findings": [],
            "assignments": [], "next_visit": None, "problems": "", "summary_note": ""}


def initial_results() -> dict:
    raw = json.loads((SAMPLES / "_initial_raw.json").read_text(encoding="utf-8"))
    out = {}
    for i, r in enumerate(raw, 1):
        ev = r["evidence"]
        status = "C" if r["status"] == "C" else ("IP" if "อยู่ระหว่าง" in ev else "NS")
        out[str(i)] = {"status": status, "evidence": ev}
    return out


def visit_results() -> dict:
    raw = json.loads((SAMPLES / "_visit2_raw.json").read_text(encoding="utf-8"))
    m = {"done": "C", "in_progress": "IP", "not_started": "NS"}
    return {str(i): {"status": m.get(r["progress"], "C" if r["status"] == "C" else "NS"),
                     "evidence": r["evidence"]} for i, r in enumerate(raw, 1)}


